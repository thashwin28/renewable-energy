clear all;
close all;
T=310;
ph2=1;
po2=1;
ifc=0;
A=69.7;
z1=-0.475;
z3=7.6e-5;
z4=-1.0*10^-4;
Rc=0.00019;
Rm=0.2;
B=0.0171;
Jmax=1600;
N=24;
for i=1:100
%=================================================================%
E_N=1.229-(0.85*10^-3*(T-298.15))+(1.31*10^-5*T*(log(ph2)+0.5*log(po2)));
%=================================================================%
co2=po2/(5.08*10^6*exp(-498/T));
z2=0.00286+0.0002*log(A)+(4.3*10^-5*log(co2));
%=================================================================%
Vact=-(z1+z2*T+z3*T*log(co2)+z4*T*log(ifc));
%=================================================================%
Vohmic=ifc*(Rm+Rc);
%=================================================================%
J=ifc/A;
Vcon=-B*log(1-(J/Jmax));
%=================================================================%
Vfc(i)=N*(E_N-Vact-Vohmic-Vcon);
IFC(i)=ifc;
ifc=ifc+0.1;
end
yyaxis left
plot(IFC,Vfc,IFC,Vfc.*IFC)
xlabel('Fuelcell Current(A)')
ylabel('Fuelcell Voltage (V)')
yyaxis right
plot(IFC,Vfc.*IFC)
ylabel('Fuelcell Power (W)')